import { readFile, writeFile } from "node:fs/promises";

const generatedPath = new URL("../src/i18n/messages.generated.ts", import.meta.url);
const outputPath = new URL("../src/i18n/catalogs.generated.ts", import.meta.url);
const targets = { "zh-TW": "zh-TW", ja: "ja", ko: "ko", es: "es", pt: "pt", fr: "fr", de: "de", it: "it", tr: "tr", ar: "ar" };
const separator = "\n⟦KCAT-40A7F2⟧\n";

function readObject(source, name) {
  const match = source.match(new RegExp(`export const ${name} = (\\{[\\s\\S]*?\\}) as const;`));
  if (!match) throw new Error(`Cannot find ${name}`);
  return JSON.parse(match[1]);
}

function batches(entries) {
  const result = [];
  let current = [], length = 0;
  for (const entry of entries) {
    if (current.length >= 20 || length + entry[1].length > 2500) { result.push(current); current = []; length = 0; }
    current.push(entry); length += entry[1].length;
  }
  if (current.length) result.push(current);
  return result;
}

async function translateBatch(items, target) {
  const url = new URL("https://translate.googleapis.com/translate_a/single");
  url.searchParams.set("client", "gtx");
  url.searchParams.set("sl", "zh-CN");
  url.searchParams.set("tl", target);
  url.searchParams.set("dt", "t");
  url.searchParams.set("q", items.map(([, value]) => value).join(separator));
  for (let attempt = 0; attempt < 5; attempt++) {
    const response = await fetch(url);
    if (response.ok) {
      const payload = await response.json();
      const translated = payload[0].map(part => part[0]).join("");
      const values = translated.split(/\s*⟦KCAT-40A7F2⟧\s*/);
      if (values.length === items.length) return values.map(value => value.trim());
    }
    await new Promise(resolve => setTimeout(resolve, 500 * 2 ** attempt));
  }
  throw new Error(`Translation failed for ${target}`);
}

function placeholders(value) {
  return [...value.matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)].map(match => match[1]).sort().join(":");
}

async function translateCatalog(entries, target, fallback) {
  const work = batches(entries);
  const catalog = {};
  let cursor = 0;
  async function worker() {
    while (cursor < work.length) {
      const index = cursor++;
      const translated = await translateBatch(work[index], target);
      work[index].forEach(([id, source], item) => {
        const value = translated[item] || fallback[id];
        catalog[id] = placeholders(value) === placeholders(source) ? value : fallback[id];
      });
      process.stdout.write(`\r${target} ${Math.min(cursor, work.length)}/${work.length}`);
    }
  }
  await Promise.all(Array.from({ length: Math.min(10, work.length) }, worker));
  process.stdout.write("\n");
  return catalog;
}

const source = await readFile(generatedPath, "utf8");
const english = readObject(source, "knowledgeEnglishMessages");
const chinese = readObject(source, "knowledgeChineseMessages");
const entries = Object.entries(chinese);
const catalogs = {};
for (const [locale, target] of Object.entries(targets)) catalogs[locale] = await translateCatalog(entries, target, english);
const localeType = Object.keys(targets).map(locale => JSON.stringify(locale)).join(" | ");
await writeFile(outputPath, `// Generated by scripts/generate-locale-catalogs.mjs. Do not hand edit.\nexport const knowledgeTranslatedCatalogs: Record<${localeType}, Record<string, string>> = ${JSON.stringify(catalogs, null, 2)};\n`);
console.log(`wrote ${outputPath.pathname}`);
